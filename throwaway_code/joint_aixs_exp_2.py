            sto_file_path = os.path.join(data_folder_path, f"{trial_type}_orientations_{COMP_METHOD.lower().replace(' ', '_')}.sto")
            print(f"Loading {COMP_METHOD} data from: {sto_file_path}")
            world_traces_alt = WorldTrace.load_from_sto_file(sto_file_path)

