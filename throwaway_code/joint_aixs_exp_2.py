            # imu_offset_error = np.linalg.norm([R_wp @ imu_offset_parent - R_wc @ imu_offset_child - delta for R_wp, R_wc, delta in zip(parent_marker.world_trace.rotations, child_marker.world_trace.rotations, r_c_p)], axis=1)

            # # Report results
            # print(f"  Marker Parent ({parent_name}) Offset: {np.round(marker_offset_parent, 4)}")
